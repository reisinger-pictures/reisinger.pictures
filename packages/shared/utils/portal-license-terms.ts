/**
 * Explicit importer for the portal's live licence-terms settings.
 *
 * Boundary rules (owner decision 2026-10-18):
 * - Only the nine fields in {@link PORTAL_TERM_FIELDS} are ever persisted; the
 *   endpoint serves many more (legal texts, prices, multipliers) and none of
 *   those may end up in the snapshot.
 * - Money values are integer **cents**, counts are positive integers and the
 *   dimensionless multiplier is a positive finite number — validated *before*
 *   anything is written.
 * - The import is explicit (`pnpm run import:portal-terms`), never part of
 *   `prebuild`, the runtime or CI. On an HTTP/parse/validation failure the
 *   existing snapshot is left untouched (atomic write, no silent fallback), so
 *   this module contains the pure logic and the caller injects the IO.
 */

export const PORTAL_LICENSE_TERMS_URL = "https://portal.reisinger.pictures/api/settings/license-terms";

/** The only portal fields the website is allowed to persist. */
export const PORTAL_TERM_FIELDS = [
  "calc_base_price",
  "calc_hourly_rate",
  "calc_images_per_hour",
  "calc_outdoor_images_per_hour",
  "calc_flatrate_multiplier",
  "srp_base_price",
  "srp_setup_fee",
  "srp_extra_image_fee",
  "srp_privacy_fee"
] as const;

export type PortalTermField = (typeof PORTAL_TERM_FIELDS)[number];
export type PortalTermValues = Record<PortalTermField, string>;

/** Money fields, stored as integer cents. */
const MONEY_FIELDS: readonly PortalTermField[] = [
  "calc_base_price",
  "calc_hourly_rate",
  "srp_base_price",
  "srp_setup_fee",
  "srp_extra_image_fee",
  "srp_privacy_fee"
];

/** Count fields, stored as positive integers. */
const COUNT_FIELDS: readonly PortalTermField[] = ["calc_images_per_hour", "calc_outdoor_images_per_hour"];

/** Dimensionless factor fields, stored as positive finite numbers. */
const MULTIPLIER_FIELDS: readonly PortalTermField[] = ["calc_flatrate_multiplier"];

function readNumber(value: unknown, field: PortalTermField): number {
  const parsed =
    typeof value === "number"
      ? value
      : typeof value === "string" && value.trim() !== ""
        ? Number(value)
        : Number.NaN;
  if (!Number.isFinite(parsed)) {
    throw new Error(`Portal licence terms: "${field}" is not a finite number (got ${JSON.stringify(value)}).`);
  }
  return parsed;
}

/**
 * Validates the raw endpoint payload and returns the nine normalised string
 * values. Throws on any missing or malformed required field; extra endpoint
 * fields are ignored on purpose.
 */
export function validatePortalTerms(payload: unknown): PortalTermValues {
  if (typeof payload !== "object" || payload === null) {
    throw new Error("Portal licence terms: payload is not an object.");
  }
  const record = payload as Record<string, unknown>;
  const result = {} as PortalTermValues;

  for (const field of PORTAL_TERM_FIELDS) {
    const value = record[field];
    if (value === null || value === undefined || value === "") {
      throw new Error(`Portal licence terms: required field "${field}" is missing.`);
    }

    const parsed = readNumber(value, field);

    if (MONEY_FIELDS.includes(field)) {
      if (!Number.isInteger(parsed) || parsed <= 0) {
        throw new Error(`Portal licence terms: "${field}" must be a positive integer of cents (got ${parsed}).`);
      }
    } else if (COUNT_FIELDS.includes(field)) {
      if (!Number.isInteger(parsed) || parsed <= 0) {
        throw new Error(`Portal licence terms: "${field}" must be a positive integer count (got ${parsed}).`);
      }
    } else if (MULTIPLIER_FIELDS.includes(field)) {
      if (!(parsed > 0)) {
        throw new Error(`Portal licence terms: "${field}" must be a positive finite factor (got ${parsed}).`);
      }
    } else {
      throw new Error(`Portal licence terms: unhandled field "${field}".`);
    }

    result[field] = String(parsed);
  }

  return result;
}

/** Removes the volatile timestamp line so unchanged terms are never rewritten. */
export function stripFetchedAt(content: string): string {
  return content.replace(/^\s*fetchedAt: .*$/m, "  fetchedAt: <unchanged>,");
}

/** Builds the checked-in snapshot content (a stable, generated TS module). */
export function buildPortalTermsArtifact(terms: PortalTermValues, fetchedAt: string): string {
  const termsLiteral = PORTAL_TERM_FIELDS.map((field) => `    ${field}: ${JSON.stringify(terms[field])}`).join(",\n");
  return `// AUTO-GENERATED by packages/tools/scripts/import-portal-license-terms.ts — do not edit by hand.
// Regenerate with: pnpm run import:portal-terms
// Source: ${PORTAL_LICENSE_TERMS_URL}
// Money values are integer cents, counts are plain counts and the multiplier is
// dimensionless. The raw portal values are stored unchanged; the public display
// performs its own psychological rounding.

export const portalLicenseTerms = {
  source: ${JSON.stringify(PORTAL_LICENSE_TERMS_URL)},
  fetchedAt: ${JSON.stringify(fetchedAt)},
  units: { money: "cents", counts: "count", multiplier: "dimensionless" },
  terms: {
${termsLiteral}
  }
} as const;

export type PortalLicenseTerms = typeof portalLicenseTerms;
`;
}

/** IO the caller injects, so the pure logic stays testable without the filesystem. */
export interface PortalTermsImportIO {
  fetchTerms(url: string): Promise<unknown>;
  readArtifact(path: string): Promise<string | null>;
  writeArtifact(path: string, content: string): Promise<void>;
}

export interface PortalTermsImportOptions {
  artifactPath: string;
  fetchedAt: string;
  url?: string;
}

/**
 * Runs one explicit import. Throws (and writes nothing) on a failed fetch,
 * parse or validation. If the normalised terms are unchanged, the snapshot —
 * including its timestamp — is left untouched and the status is "unchanged".
 */
export async function runPortalTermsImport(
  options: PortalTermsImportOptions,
  io: PortalTermsImportIO
): Promise<{ status: "written" | "unchanged"; terms: PortalTermValues }> {
  const url = options.url ?? PORTAL_LICENSE_TERMS_URL;
  const payload = await io.fetchTerms(url);
  const terms = validatePortalTerms(payload);
  const content = buildPortalTermsArtifact(terms, options.fetchedAt);

  const existing = await io.readArtifact(options.artifactPath);
  if (existing !== null && stripFetchedAt(existing) === stripFetchedAt(content)) {
    return { status: "unchanged", terms };
  }

  await io.writeArtifact(options.artifactPath, content);
  return { status: "written", terms };
}
